# ---------- Шаг 4. Разбор фразы пользователя ----------
АЛИАСЫ_СТРАН = {"US": r"сша|америк|штатах|штатов", "GB": r"англи|великобритани", "BY": r"белорус|беларус",
                "KR": r"коре", "AE": r"оаэ|эмират", "CN": r"кита|китае"}


def _основа(название):
    return re.sub(r"[аяйьыиеуюо]+$", "", название.lower())


def найти_страну(текст):
    from countries import страны
    нижний = текст.lower()
    for код, данные in страны.items():
        шаблон = АЛИАСЫ_СТРАН.get(код)
        шаблоны = [r"(?<![а-я])" + (шаблон if шаблон else re.escape(_основа(данные["название страны"].split()[-1])))]
        if any(re.search(ш, нижний) for ш in шаблоны):
            return код
    return None


def найти_число(текст):
    м = re.search(r"(\d{1,3}(?:[  ]\d{3})+|\d+)(\s*(?:тыс\w*|k|к\b))?", текст.lower())
    if not м:
        return None
    число = int(re.sub(r"\s", "", м.group(1)))
    return число * 1000 if м.group(2) and "тыс" in м.group(2) or (м.group(2) or "").strip() in ("k", "к") else число


def разобрать_запрос(текст):
    нижний = текст.lower()
    виды = []
    if re.search(r"биометр|днк|геном|лиц[ао]|отпечат", нижний):
        виды.append("биометрические")
    if re.search(r"специальн|здоров|медицин|диагноз|заболеван|религи|национальн", нижний):
        виды.append("специальные")
    if re.search(r"общедоступн", нижний):
        виды.append("общедоступные")
    действие = None
    if re.search(r"утечк|происшеств|взлом|слит|похищен|инцидент", нижний):
        действие = "происшествие"
    elif re.search(r"передат|передач|отправ|перевест|вывез", нижний):
        действие = "передача"
    return {"исходный текст": текст, "страна": найти_страну(текст), "число людей": найти_число(текст),
            "виды данных": виды or ["иные"], "виды указаны": bool(виды), "действие": действие,
            "повторно": bool(re.search(r"повторн|снова|опять|ещё раз|еще раз|вновь|уже была", нижний))}


def обработать_запрос(разбор, организация):
    """Возвращает словарь с итогами по запросу пользователя."""
    from country_check import проверить_страну
    from fine_calculator import рассчитать_штраф
    р = {"разбор": разбор, "приговор": None, "условия": [], "ссылки": [], "баллы": 0, "риск": 0, "пояснения": []}
    выручка = организация["годовая выручка в рублях"]
    if разбор["действие"] == "передача":
        if not разбор["страна"]:
            р["пояснения"].append("Страна не распознана — укажите страну получателя.")
            return р
        с = проверить_страну(разбор["страна"])
        р.update({"приговор": с["приговор"], "условия": list(с["условия"]), "ссылки": с["ссылки на закон"],
                  "страна": с["название"], "дней": с["число дней ожидания"]})
        if "биометрические" in разбор["виды данных"] or "специальные" in разбор["виды данных"]:
            р["условия"].append("Нужно отдельное письменное согласие на данные особых видов (ст. 10, 11 152-ФЗ)")
        if с["приговор"] == "запрещено":
            р["баллы"] = 8
        elif с["приговор"] == "разрешено при условиях":
            р["баллы"] = 3
            р["риск"] = рассчитать_штраф("нарушение по согласию", разбор["число людей"] or 0, False, выручка)["наибольший размер штрафа"]
    elif разбор["действие"] == "происшествие":
        n = разбор["число людей"] or 0
        вид = "утечка малого размера" if n <= 10_000 else "утечка среднего размера" if n <= 100_000 else "утечка крупного размера"
        расчёты = [рассчитать_штраф(вид, n, разбор["повторно"], выручка)]
        балл = ВЕС_УТЕЧКИ[вид]
        if "биометрические" in разбор["виды данных"]:
            расчёты.append(рассчитать_штраф("нарушение по биометрии", n, разбор["повторно"], выручка))
            балл += 10
        if "специальные" in разбор["виды данных"]:
            балл += 5
        if разбор["повторно"]:
            балл += 10
        лучший = max(расчёты, key=lambda x: x["наибольший размер штрафа"])
        р.update({"приговор": "утечка: " + вид, "ссылки": ["ст. 21 ч. 3.1 152-ФЗ", "ст. 13.11 КоАП РФ"],
                  "баллы": балл, "риск": лучший["наибольший размер штрафа"], "расчёт штрафа": лучший,
                  "страна": разбор["страна"] and None})
        р["условия"] = ["Уведомить РКН в течение 24 часов", "Направить результаты расследования в течение 72 часов"]
        from notification_builder import создать_уведомление
        ув = создать_уведомление({"дата и время обнаружения": datetime.now(), "число пострадавших людей": n,
                                  "виды данных": разбор["виды данных"], "причина утечки": "уточняется",
                                  "принятые меры": "доступ ограничен, начато расследование",
                                  "расследование завершено": False}, ФАЙЛ_УВЕДОМЛЕНИЯ,
                                 ответственный=организация["ответственный за обработку данных"])
        р["пояснения"].append(f"Сформировано {ув['вид']} уведомление: {ФАЙЛ_УВЕДОМЛЕНИЯ}")
    else:
        р["пояснения"].append("Не удалось определить действие (передача или происшествие).")
    return р


# ---------- Шаг 5. Итоговый отчёт ----------
def рубли(х):
    return f"{int(х):,}".replace(",", " ") + " руб."


def собрать_отчёт(организация, документы, нарушения_расчёт, запросы):
    L = ["ИТОГОВЫЙ ОТЧЁТ О СООТВЕТСТВИИ ТРЕБОВАНИЯМ 152-ФЗ", "=" * 60, "", "1. ОБЩИЕ СВЕДЕНИЯ ОБ ОРГАНИЗАЦИИ"]
    L += [f"  Название: {организация['название']}", f"  Отрасль: {организация['отрасль']}",
          f"  Год основания: {организация['год основания']}",
          f"  Годовая выручка: {рубли(организация['годовая выручка в рублях'])}",
          f"  Сотрудников: {организация['количество сотрудников']}",
          f"  Людей в базе: {организация['количество человек, чьи данные хранятся в базе']:,}".replace(",", " "),
          f"  Ответственный: {организация['ответственный за обработку данных']}", "", "2. ИТОГИ ПРОВЕРКИ ДОКУМЕНТОВ"]
    for д in документы:
        L.append(f"  {д['файл']}: {д['состояние']} — {д['причина']} Штраф: {рубли(д['штраф'])}")
    L += ["", "3. НАЙДЕННЫЕ НАРУШЕНИЯ"]
    for x in нарушения_расчёт:
        н, р = x["нарушение"], x["расчёт"]
        L += [f"  №{н['номер']} ({н['вид']}), запись карты данных {н['запись карты данных']}: {н['описание']}",
              f"     Норма: {н['норма права']}",
              f"     Заложенный штраф: {рубли(н['размер штрафа в рублях'])}; расчёт: "
              f"{рубли(р['наименьший размер штрафа'])} – {рубли(р['наибольший размер штрафа'])}",
              f"     Исправление: {н['что нужно сделать']}"]
    L += ["", "4. РАЗБОР ЗАПРОСОВ ПОЛЬЗОВАТЕЛЯ"]
    if not запросы:
        L.append("  Запросов пока не было.")
    for i, з in enumerate(запросы, 1):
        р, ра = з["разбор"], з
        L += [f"  Запрос {i}: «{р['исходный текст']}»",
              f"     Действие: {р['действие'] or 'не определено'}; страна: {ра.get('страна') or р['страна'] or '—'}; "
              f"людей: {р['число людей'] or '—'}; виды данных: {', '.join(р['виды данных'])}"
              + ("; повторно" if р["повторно"] else ""),
              f"     Приговор: {ра['приговор'] or '—'}",
              f"     Условия: {'; '.join(ра['условия']) or '—'}",
              f"     Ссылки на закон: {'; '.join(ра['ссылки']) or '—'}"]
        if "расчёт штрафа" in ра:
            рш = ра["расчёт штрафа"]
            L.append(f"     Штраф: {рубли(рш['наименьший размер штрафа'])} – {рубли(рш['наибольший размер штрафа'])}; "
                     f"оборотный: {'да' if рш['оборотный штраф применим'] else 'нет'}")
        L += [f"     {п}" for п in ра["пояснения"]]

    # Оценка
    баллы = sum(ВЕС_НАРУШЕНИЯ.get(x["нарушение"]["вид для расчёта штрафа"], 10) for x in нарушения_расчёт)
    баллы += sum(ВЕС_ДОКУМЕНТА[д["состояние"]] for д in документы) + sum(з["баллы"] for з in запросы)
    оценка = max(0, 100 - баллы)
    риск = sum(x["расчёт"]["наибольший размер штрафа"] for x in нарушения_расчёт)
    риск += sum(д["штраф"] for д in документы) + sum(з["риск"] for з in запросы)
    действия = [f"Нарушение №{x['нарушение']['номер']}: {x['нарушение']['что нужно сделать']}"
                for x in sorted(нарушения_расчёт, key=lambda x: -x["расчёт"]["наибольший размер штрафа"])]
    for д in документы:
        if д["состояние"] != "в порядке":
            действия.append(f"Исправить документ {д['файл']}: {д['причина']}")
    for з in запросы:
        if з["приговор"] and з["приговор"].startswith("утечка"):
            действия.append("Уложиться в 24/72 часа по утечке и направить уведомления в РКН")
    L += ["", "5. ИТОГОВАЯ ОЦЕНКА", f"  Оценка соответствия: {оценка} из 100 (штрафных баллов: {баллы})",
          f"  Общий риск штрафов: {рубли(риск)}", "  Первоочередные действия:"]
    L += [f"   {i}. {д}" for i, д in enumerate(действия[:5], 1)]
    return "\n".join(L) + "\n"


def сохранить_отчёт(текст):
    os.makedirs(os.path.dirname(ФАЙЛ_ИТОГОВОГО_ОТЧЁТА), exist_ok=True)
    with open(ФАЙЛ_ИТОГОВОГО_ОТЧЁТА, "w", encoding="utf-8") as ф:
        ф.write(текст)


# ---------- Шаг 6. Разговорный цикл ----------
def главная():
    организация, _карта, нарушения, _заявки = загрузить_артефакты()
    документы = проверить_документы()
    расчёты = пересчитать_нарушения(нарушения, организация)
    запросы = []
    сохранить_отчёт(собрать_отчёт(организация, документы, расчёты, запросы))
    print(f"Здравствуйте! Симулятор проверки соответствия 152-ФЗ — {организация['название']}.")
    print("Опишите ситуацию, например: «Хотим передать данные 20 000 клиентов в Китай для аналитики»")
    print("или «Обнаружена утечка 5 000 записей из базы в США». Для завершения введите «выход».")
    while True:
        try:
            фраза = input("> ").strip()
        except EOFError:
            break
        if фраза.lower() in СЛОВА_ВЫХОДА:
            print("До свидания! Итоговый отчёт: " + ФАЙЛ_ИТОГОВОГО_ОТЧЁТА)
            break
        if not фраза:
            continue
        итог = обработать_запрос(разбор_запроса := разобрать_запрос(фраза), организация)
        запросы.append(итог)
        отчёт = собрать_отчёт(организация, документы, расчёты, запросы)
        сохранить_отчёт(отчёт)
        print(f"Страна: {итог.get('страна') or разбор_запроса['страна'] or '—'}; приговор: {итог['приговор'] or '—'}")
        for у in итог["условия"] + итог["пояснения"]:
            print("  - " + у)
        print("Отчёт обновлён.")


if __name__ == "__main__":
    главная()
