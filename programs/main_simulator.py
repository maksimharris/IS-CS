# ---------- Шаг 1. Загрузка артефактов ----------
def ошибка_и_выход(сообщение):
    print("ОШИБКА ЗАГРУЗКИ: " + сообщение)
    sys.exit(1)


def загрузить_артефакты():
    try:
        from organization import организация
        from data_map import карта_данных
        from violations import нарушения
        from countries import страны
        from transfer_requests import заявки
    except Exception as е:  # неполный/испорченный файл с данными
        ошибка_и_выход(f"не удалось подключить данные: {е!r}")
    обязательные = ["название", "отрасль", "год основания", "годовая выручка в рублях", "количество сотрудников",
                    "количество человек, чьи данные хранятся в базе", "список присутствующих видов данных",
                    "признак наличия происшествий за 2024-2025 годы", "список отделений",
                    "список стран для расширения деятельности", "ответственный за обработку данных"]
    for п in обязательные:
        if п not in организация:
            ошибка_и_выход(f"в паспорте организации нет поля «{п}»")
    if sum(о["число людей"] for о in организация["список отделений"]) != \
            организация["количество человек, чьи данные хранятся в базе"]:
        ошибка_и_выход("сумма людей по отделениям не совпадает с общим числом людей в паспорте")
    if len(карта_данных.get("записи", [])) < 15:
        ошибка_и_выход("в карте данных меньше 15 записей")
    допустимые = {"общедоступные", "специальные", "биометрические", "иные"}
    for з in карта_данных["записи"]:
        if з.get("вид данных") not in допустимые:
            ошибка_и_выход(f"запись {з.get('номер')} карты данных: недопустимый вид данных")
    if len(нарушения.get("список", [])) != 3:
        ошибка_и_выход("в файле нарушений должно быть ровно 3 записи")
    if len(страны) < 20:
        ошибка_и_выход("в справочнике меньше 20 стран")
    if len(заявки) != 3:
        ошибка_и_выход("в файле заявок должно быть 3 заявки")
    return организация, карта_данных, нарушения, заявки


# ---------- Шаг 2. Проверка документов ----------
def проверить_документы():
    from consent_check import проверить_согласие, вид_по_имени_файла, ПАПКА_ДОКУМЕНТОВ
    итог = []
    for имя in sorted(os.listdir(ПАПКА_ДОКУМЕНТОВ)):
        if not имя.endswith(".txt"):
            continue
        текст = open(os.path.join(ПАПКА_ДОКУМЕНТОВ, имя), encoding="utf-8").read()
        if "consent" in имя:
            р = проверить_согласие(текст, вид_по_имени_файла(имя))
            итог.append({"файл": имя, "состояние": р["состояние"], "причина": р["пояснение"],
                         "штраф": р["размер возможного штрафа в рублях"]})
        elif "policy" in имя:
            слов = len(текст.split())
            нет = [р for р in ("цел", "правовые основания", "срок", "прав", "контакт") if р not in текст.lower()]
            ок = слов >= 1500 and not нет
            итог.append({"файл": имя, "состояние": "в порядке" if ок else "замечание",
                         "причина": f"{слов} слов; " + ("все разделы на месте" if not нет else "нет разделов: " + ", ".join(нет)),
                         "штраф": 0 if ок else 100_000})
        else:  # образец уведомления
            ок = all(п in текст for п in ("{вид_уведомления}", "{число_людей}", "{дата_обнаружения}"))
            итог.append({"файл": имя, "состояние": "в порядке" if ок else "замечание",
                         "причина": "шаблон содержит поля для подстановки" if ок else "в шаблоне нет обязательных полей",
                         "штраф": 0 if ок else 100_000})
    return итог


