# -*- coding: utf-8 -*-
"""Задание 3.2. Проверка страны назначения. Данные берутся из data/countries.py."""
import os
import sys

КОРЕНЬ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(КОРЕНЬ, "data"))
from countries import страны  # подключение справочника, а не хранение внутри функции

ДНЕЙ_ОЖИДАНИЯ_БЕЗ_ЗАЩИТЫ = 10  # рабочих дней, ст. 12 ч. 12 152-ФЗ


def проверить_страну(код):
    """Возвращает словарь: код, название, приговор, условия, ссылки на закон, дней ожидания."""
    код = код.upper().strip()
    if код not in страны:
        return {"код": код, "название": "неизвестная страна", "приговор": "запрещено",
                "условия": ["Страна отсутствует в справочнике — передача недопустима до проверки"],
                "ссылки на закон": ["ст. 12 152-ФЗ"], "число дней ожидания": 0}
    с = страны[код]
    ссылки = ["ст. 12 152-ФЗ", с["ссылка на источник"]]
    условия = ["Направить в Роскомнадзор уведомление о намерении передавать данные (ст. 12 ч. 4 152-ФЗ)"]

    if с["особый режим"] == "запрещено":
        return {"код": код, "название": с["название страны"], "приговор": "запрещено",
                "условия": [с["правила передачи"]], "ссылки на закон": ссылки, "число дней ожидания": 0}

    if с["достаточная защита по версии Роскомнадзора"] or с["входит в Конвенцию 108"]:
        приговор, дней = "разрешено", 0
        условия.append("Передачу можно начать сразу после направления уведомления")
    else:
        приговор, дней = "разрешено при условиях", ДНЕЙ_ОЖИДАНИЯ_БЕЗ_ЗАЩИТЫ
        условия += ["Оценка вреда субъектам и мер защиты у получателя (ст. 12 ч. 5 152-ФЗ)",
                    f"Выдержать {ДНЕЙ_ОЖИДАНИЯ_БЕЗ_ЗАЩИТЫ} рабочих дней с даты уведомления РКН",
                    "Получить от получателя обязательство по обеспечению конфиденциальности"]
    if с["особый режим"] == "особый":
        приговор = "разрешено при условиях"
        дней = max(дней, ДНЕЙ_ОЖИДАНИЯ_БЕЗ_ЗАЩИТЫ)
        условия.append("Особый режим: " + с["правила передачи"])
    return {"код": код, "название": с["название страны"], "приговор": приговор,
            "условия": условия, "ссылки на закон": ссылки, "число дней ожидания": дней}


if __name__ == "__main__":
    for к in ("IL", "CN", "UA", "ZZ"):
        print(проверить_страну(к))
